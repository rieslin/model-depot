def t(lang, key, **params):
    """The sentence for `key` in `lang`, with {name} places filled from params. Unknown keys come back as they are."""
    row = STRINGS.get(key)
    if row is None:
        return key
    text = row[LANGS.index(lang)] if lang in LANGS else row[1]
    if params:
        try:
            return text.format(**params)
        except (KeyError, IndexError, ValueError):
            return text
    return text
